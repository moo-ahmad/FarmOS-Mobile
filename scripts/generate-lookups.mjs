// Generates src/lib/lookups/codes.ts from the FarmOS lookup catalogue — the
// `GET /api/lookups` response (LookupValueDto[]), i.e. every backend enum
// member with its stable `code` and its wire `value` (= lookup_id).
//
// By default it reads the checked-in snapshot at docs/lookups.json. To refresh
// that snapshot from a running API (the endpoint needs a signed-in user):
//
//   LOOKUPS_SPEC=https://localhost:7229/api/lookups?includeInactive=true \
//   LOOKUPS_TOKEN=<access token> NODE_TLS_REJECT_UNAUTHORIZED=0 \
//   pnpm lookups:generate
//
// A URL source also rewrites docs/lookups.json, so the diff shows up in review.
// Like api:generate, CI can run this and `git diff --exit-code` for drift.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import * as prettier from 'prettier';

const SNAPSHOT = 'docs/lookups.json';
const OUTPUT = 'src/lib/lookups/codes.ts';
const source = process.env.LOOKUPS_SPEC ?? SNAPSHOT;

let rows;
if (/^https?:\/\//i.test(source)) {
  const token = process.env.LOOKUPS_TOKEN;
  if (!token) {
    console.error('LOOKUPS_TOKEN is required when LOOKUPS_SPEC is a URL.');
    process.exit(1);
  }
  const response = await fetch(source, {
    headers: { Authorization: `Bearer ${token}` },
  });
  if (!response.ok) {
    console.error(`GET ${source} failed: HTTP ${response.status}`);
    process.exit(1);
  }
  rows = await response.json();
  writeFileSync(SNAPSHOT, JSON.stringify(rows, null, 2) + '\n');
  console.log(`Refreshed ${SNAPSHOT} from ${source}`);
} else {
  rows = JSON.parse(readFileSync(resolve(process.cwd(), source), 'utf8'));
}

// Retired members stay out of the constants (nothing new should send them);
// display of historic values goes through the API's own labels.
const active = rows.filter((row) => row.isActive);

/** @type {Map<string, typeof active>} */
const byType = new Map();
for (const row of active) {
  const list = byType.get(row.lookupType) ?? [];
  list.push(row);
  byType.set(row.lookupType, list);
}
for (const list of byType.values()) {
  list.sort((a, b) => a.sortOrder - b.sortOrder);
}

const isIdentifier = (s) => /^[A-Za-z_$][\w$]*$/.test(s);
const key = (s) => (isIdentifier(s) ? s : JSON.stringify(s));

const valuesBlock = [...byType]
  .map(
    ([type, list]) =>
      `  ${key(type)}: {\n${list
        .map((row) => `    ${key(row.code)}: ${row.value},`)
        .join('\n')}\n  },`,
  )
  .join('\n');

const namesBlock = [...byType]
  .map(
    ([type, list]) =>
      `  ${key(type)}: {\n${list
        .map((row) => `    ${key(row.code)}: ${JSON.stringify(row.name)},`)
        .join('\n')}\n  },`,
  )
  .join('\n');

const flagsTypes = [...byType]
  .filter(([, list]) => list.some((row) => row.isFlags))
  .map(([type]) => JSON.stringify(type));

const code = `// AUTO-GENERATED by \`pnpm lookups:generate\` from the FarmOS lookup catalogue.
// Source: ${source}
// Do not edit by hand.

/**
 * Every backend enum, by lookup type and stable member code, mapped to the
 * number its column stores and the API sends/accepts (the \`lookup_id\`,
 * \`typeId * 1000 + n\`). Switch on the code; never hard-code the number.
 */
export const Lookup = {
${valuesBlock}
} as const;

/**
 * The API's display label for each member (\`LookupValueDto.name\`). A
 * default for UI copy — screens may still word things their own way.
 */
export const LookupName = {
${namesBlock}
} as const satisfies { [T in keyof typeof Lookup]: Record<keyof (typeof Lookup)[T], string> };

/** \`[Flags]\` lookup types: values are bits and may be combined. */
export const LOOKUP_FLAGS_TYPES = [${flagsTypes.join(', ')}] as const;
`;

const config = await prettier.resolveConfig(OUTPUT);
writeFileSync(
  OUTPUT,
  await prettier.format(code, { ...config, parser: 'typescript' }),
);
console.log(
  `Wrote ${OUTPUT}: ${active.length} values across ${byType.size} types`,
);
