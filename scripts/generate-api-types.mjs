// Generates src/api/schema.d.ts from the FarmOS .NET OpenAPI document using
// openapi-typescript. Point OPENAPI_SPEC at the running API's OpenAPI URL
// (e.g. https://localhost:5001/openapi/v1.json) or a local file path.
//
// In CI this is run and `git diff --exit-code` fails the build if the checked-in
// types have drifted from the live contract.

import { existsSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';

const OUTPUT = 'src/api/schema.d.ts';
const source = process.env.OPENAPI_SPEC ?? 'docs/openapi.json';

let input;
if (/^https?:\/\//i.test(source)) {
  input = new URL(source);
} else {
  const absolute = resolve(process.cwd(), source);
  if (!existsSync(absolute)) {
    console.error(`OpenAPI spec not found at "${source}".`);
    console.error(
      'Set OPENAPI_SPEC to the FarmOS OpenAPI document URL or a local file ' +
        'path, then re-run `pnpm api:generate`.',
    );
    process.exit(1);
  }
  input = pathToFileURL(absolute);
}

const banner =
  '// AUTO-GENERATED by `pnpm api:generate` from the FarmOS OpenAPI document.\n' +
  `// Source: ${source}\n` +
  '// Do not edit by hand.\n\n';

const ast = await openapiTS(input);
writeFileSync(OUTPUT, banner + astToString(ast));
console.log(`Wrote ${OUTPUT} from ${source}`);
