// Turns the drizzle-kit output (`.sql` files + `_journal.json`) into a single
// TypeScript module that inlines every migration's SQL. This keeps runtime
// migrations bundler-agnostic — no Metro/babel `.sql` inlining plugin needed —
// and is run automatically after `drizzle-kit generate` (see `db:generate`).

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const migrationsDir = join(scriptDir, '..', 'src', 'db', 'migrations');

const journal = JSON.parse(
  readFileSync(join(migrationsDir, 'meta', '_journal.json'), 'utf8'),
);

/** @type {Record<string, string>} */
const migrations = {};
for (const entry of journal.entries) {
  const sql = readFileSync(join(migrationsDir, `${entry.tag}.sql`), 'utf8');
  const key = `m${String(entry.idx).padStart(4, '0')}`;
  migrations[key] = sql;
}

const bundle = {
  journal: {
    entries: journal.entries.map((e) => ({
      idx: e.idx,
      when: e.when,
      tag: e.tag,
      breakpoints: e.breakpoints,
    })),
  },
  migrations,
};

const banner =
  '// AUTO-GENERATED by scripts/build-migrations.mjs — do not edit.\n' +
  '// Regenerate with `pnpm db:generate` after changing the schema.\n';

const contents = `${banner}
const bundle = ${JSON.stringify(bundle, null, 2)};

export default bundle;
`;

writeFileSync(join(migrationsDir, 'bundle.ts'), contents, 'utf8');
console.log(
  `Wrote src/db/migrations/bundle.ts (${journal.entries.length} migration(s)).`,
);
